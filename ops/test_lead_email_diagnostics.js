const assert = require('node:assert/strict');
const { renderLeadDiagnostics } = require('./lead_email_diagnostics');
const empty = renderLeadDiagnostics({}, 'RCN');
assert(empty.includes('destination, travel_date, duration, budget, guests'));
assert(empty.includes('Not captured / not supplied'));
assert(!empty.includes('undefined'));
const lead = {first_name: '<script>alert(1)</script>', email: 'person@example.com', user_agent: '<img src=x onerror=alert(1)>', ip_address: '192.0.2.1', utm_id: '123', campaign_name: 'Test campaign', time_on_page: 0, honeypot_filled: false, email_mx_valid: false, risk_flags: ['short_visit'], action_token: 'SECRET_TOKEN', hashed_email: 'SECRET_HASH', destination: 'Danube', travel_date:'2027', duration:'7',budget:'5000',guests:'2'};
const before = JSON.stringify(lead);
const full = renderLeadDiagnostics(lead, 'DCT');
assert(full.includes('&lt;script&gt;'));
assert(!full.includes('<script>'));
assert(!full.includes('<img'));
assert(full.includes('Test campaign'));
assert(full.includes('192.0.2.1'));
assert(full.includes('>0</td>'));
assert(full.includes('>No</td>'));
assert(!full.includes('SECRET_'));
assert.equal(JSON.stringify(lead), before);
assert(full.includes('defaults may be present'));
console.log('Diagnostics renderer: missing fields, escaping, false/zero, campaign, no secret leakage and no mutation passed.');
